import {
  GoogleSignin,
  isErrorWithCode,
  isSuccessResponse,
  statusCodes,
} from '@react-native-google-signin/google-signin';

let configured = false;

/** Idempotent — safe to call on every sign-in attempt. */
function ensureConfigured(): void {
  if (configured) return;
  GoogleSignin.configure({
    // The backend verifies the ID token's audience against this same
    // client — Android needs it too, not just iOS (Google's ID tokens are
    // always issued for the web client, regardless of which platform's
    // native picker was used to sign in).
    webClientId: process.env.EXPO_PUBLIC_GOOGLE_WEB_CLIENT_ID,
    // Set explicitly rather than relying on GoogleService-Info.plist's
    // CLIENT_ID — that plist was generated by Firebase, not by linking this
    // standalone iOS OAuth client, so it isn't guaranteed to match.
    iosClientId: process.env.EXPO_PUBLIC_GOOGLE_IOS_CLIENT_ID,
    offlineAccess: false,
  });
  configured = true;
}

export type GoogleSignInResult =
  | { status: 'success'; idToken: string }
  | { status: 'cancelled' }
  | { status: 'play-services-unavailable' }
  | { status: 'error'; message: string };

// Some users report the "Continue with Google" button spinning forever with
// no error at all — confirmed (via backend request logs) that the request
// never even leaves the device, so the native module's promise itself is
// the thing not settling. Racing it against a timeout guarantees the UI
// always reaches a definite outcome, whatever is actually stuck natively.
function withTimeout<T>(promise: Promise<T>, ms: number, timeoutMessage: string): Promise<T> {
  return new Promise((resolve, reject) => {
    const timer = setTimeout(() => reject(new Error(timeoutMessage)), ms);
    promise.then(
      (value) => {
        clearTimeout(timer);
        resolve(value);
      },
      (error) => {
        clearTimeout(timer);
        reject(error);
      },
    );
  });
}

export async function signInWithGoogle(): Promise<GoogleSignInResult> {
  ensureConfigured();
  try {
    await withTimeout(
      GoogleSignin.hasPlayServices({ showPlayServicesUpdateDialog: true }),
      15000,
      'Google Play Services check timed out',
    );
    // Long timeout — this is the step where the user actually picks an
    // account (and possibly does 2FA), so it must comfortably outlast normal
    // human interaction while still recovering if it's genuinely stuck.
    const response = await withTimeout(GoogleSignin.signIn(), 90000, 'Google sign-in timed out');

    if (!isSuccessResponse(response)) {
      return { status: 'cancelled' };
    }

    const idToken = response.data.idToken;
    if (!idToken) {
      return { status: 'error', message: 'Google did not return an ID token' };
    }

    return { status: 'success', idToken };
  } catch (error) {
    if (isErrorWithCode(error)) {
      switch (error.code) {
        case statusCodes.SIGN_IN_CANCELLED:
          return { status: 'cancelled' };
        case statusCodes.PLAY_SERVICES_NOT_AVAILABLE:
          return { status: 'play-services-unavailable' };
        default:
          return { status: 'error', message: error.message ?? String(error.code) };
      }
    }
    return { status: 'error', message: error instanceof Error ? error.message : String(error) };
  }
}
